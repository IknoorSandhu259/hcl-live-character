"""Hour 6: the two local audio cues, and the places they are allowed to sound.

Nothing here opens a device or makes a paid call. The cues are generated by
``media_cues`` in-process, and every wiring test drives the real engagement
loop headlessly against the same fakes the Hour 5 tests use.

Two properties are load bearing and are why most of this file exists.

**One speaker, one deadline.** The cues go down the same
``prepare``/``play`` interface as speech and extend the same
``VoiceSession`` quiet deadline, so a cue that is sounding blocks a push-to-talk
exactly as a sentence does, and the goal's closing line waits behind the music.

**Only a verified goal earns the music.** The flourish is armed in the single
branch that turned the light on, so every unsuccessful ending is silent.

    python -m pytest tests -q
"""

