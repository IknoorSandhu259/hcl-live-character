def test_a_verified_goal_plays_the_music_between_the_light_and_the_words(
    monkeypatch, capsys
):
    log = _spy_lamp(monkeypatch)
    player = CuePlayer(log=log)
    brain = _verifying_brain()

    _run_goal(monkeypatch, brain, player)
    out = capsys.readouterr().out

    assert "light ON" in out
    timeline = [entry for entry in log if entry in ("look_left", "light_on", "music", "speech")]
    assert timeline == ["look_left", "light_on", "music", "speech"]
    assert player.played == [ACK, MUSIC, b"speech"]
    assert brain.spoken == [goal_module.found_line("mug")]


@pytest.mark.parametrize(
    "sightings",
    [
        # Never found: no turn, no light, no music.
        [sighting_json(found=False, location="unknown")],
        # Found and aimed at, but gone by the second look.
        [sighting_json(), sighting_json(found=False, location="unknown")],
        # Found twice, but it moved to the other side while the head turned.
        [sighting_json(location="left"), sighting_json(location="right")],
    ],
    ids=["never-found", "lost-before-verification", "moved-during-the-turn"],
)
def test_an_unsuccessful_goal_never_plays_the_music(monkeypatch, capsys, sightings):
    log = _spy_lamp(monkeypatch)
    player = CuePlayer(log=log)
    brain = _LocatingBrain(*sightings)

    _run_goal(monkeypatch, brain, player)
    capsys.readouterr()

    assert "light_on" not in log
    assert MUSIC not in player.played
    assert "music" not in log
    # The character still says how it went, and the lamp still ends dark.
    assert player.played[-1] == b"speech"
    assert log[-1] == "light_off"


def test_the_music_waits_until_an_existing_spoken_playback_has_finished(
    monkeypatch, capsys
):
    """The reply accepting the goal claims 30 s -- longer than the whole script."""
    log = _spy_lamp(monkeypatch)
    player = CuePlayer(log=log)
    brain = _verifying_brain()
    goals = _inline_goal_session(brain, player)

    engagement_demo.run(
        preview=False,
        headless=True,
        sensor=_FrameSensor([(True, 8.0)]),
        voice_factory=lambda _lamp: GoalTurn(speech_seconds=30.0),
        talk_key=ScriptedTalkKey(40),
        goals=goals,
        player=player,
    )
    capsys.readouterr()

    # The visual half ran to completion and the light is on...
    assert "light_on" in log
    # ...but the music never went out on top of the reply, and neither did the
    # closing sentence that waits behind it.
    assert player.played == [ACK]
    assert brain.spoken == []
    assert goals.held is True
    assert goals.music_pending is True


def test_the_closing_speech_waits_until_the_music_has_finished(monkeypatch, capsys):
    log = _spy_lamp(monkeypatch)
    player = CuePlayer(log=log, cue_seconds=1.0)
    brain = _verifying_brain()

    _run_goal(monkeypatch, brain, player)
    capsys.readouterr()

    assert player.played == [ACK, MUSIC, b"speech"]
    # A whole second of flourish separates the two, because the music extended
    # the same deadline the closing line waits on.
    assert player.started("speech") - player.started("music") >= 0.95


def test_a_failing_music_cue_is_reported_and_the_goal_still_stands(
    monkeypatch, capsys
):
    """A decoration that failed must not undo a verified goal or its light."""
    log = _spy_lamp(monkeypatch)
    player = CuePlayer(log=log, fail_on=(MUSIC,))
    brain = _verifying_brain()

    _run_goal(monkeypatch, brain, player)
    captured = capsys.readouterr()

    assert "could not play the success music" in captured.err
    assert "light ON" in captured.out
    # The light came on and stayed on until the demo shut down...
    assert log.index("light_on") < log.index("speech")
    assert "light_off" not in log[log.index("light_on"): log.index("speech")]
    # ...and the character still said how it went.
    assert player.played == [ACK, b"speech"]
    assert brain.spoken == [goal_module.found_line("mug")]


def test_the_live_loop_survives_both_cues_failing(monkeypatch, capsys):
    log = _spy_lamp(monkeypatch)
    player = CuePlayer(log=log, fail_on=(ACK, MUSIC))
    brain = _verifying_brain()

    _run_goal(monkeypatch, brain, player, script=[(True, 6.0), (False, 4.0)])
    captured = capsys.readouterr()

    assert "could not play the engagement acknowledgement" in captured.err
    assert "could not play the success music" in captured.err
    # The whole demo ran on, engagement, goal and disengagement alike.
    assert "ENGAGED -> IDLE" in captured.out
    assert "light_on" in log
    assert player.played == [b"speech"]
    assert log[-1] == "light_off"


