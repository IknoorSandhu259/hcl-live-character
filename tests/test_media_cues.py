def _label(wav_bytes: bytes) -> str:
    """What the shared speaker was asked to make: one of three things."""
    if wav_bytes == ACK:
        return "sfx"
    if wav_bytes == MUSIC:
        return "music"
    return "speech"


class CuePlayer:
    """Records every playback with its label and the moment it started.

    The same two-phase interface as the real speaker, and the length it reports
    is honest, so the loop's quiet deadline behaves as it does live. *fail_on*
    is a tuple of WAV payloads whose ``prepare`` raises, which is how the
    failure tests break exactly one cue and nothing else.
    """

    def __init__(self, log=None, cue_seconds=0.0, speech_seconds=0.0, fail_on=()):
        self.log = log if log is not None else []
        self.cue_seconds = cue_seconds
        self.speech_seconds = speech_seconds
        self.fail_on = tuple(fail_on)
        self.played: list[bytes] = []
        #: (label, monotonic time) per playback, for the ordering assertions.
        self.times: list[tuple] = []

    def prepare(self, wav_bytes):
        if wav_bytes in self.fail_on:
            raise audio_io.AudioError("the output device went away")
        seconds = (
            self.cue_seconds if wav_bytes in (ACK, MUSIC) else self.speech_seconds
        )
        return audio_io.PreparedPlayback(
            samples=wav_bytes, sample_rate=16_000, channels=1, seconds=seconds
        )

    def play(self, prepared) -> None:
        label = _label(prepared.samples)
        self.played.append(prepared.samples)
        self.log.append(label)
        self.times.append((label, time.monotonic()))

    def started(self, label: str) -> float:
        """When *label* first sounded. Fails the test if it never did."""
        for played, moment in self.times:
            if played == label:
                return moment
        raise AssertionError(f"{label!r} never played")


def _run_goal(monkeypatch, brain, player, *, speech_seconds=0.0, script=None, press=40):
    """Drive the real loop headlessly through one spoken goal."""
    engagement_demo.run(
        preview=False,
        headless=True,
        sensor=_FrameSensor(script if script is not None else [(True, 8.0)]),
        voice_factory=lambda _lamp: GoalTurn(speech_seconds=speech_seconds),
        talk_key=ScriptedTalkKey(press),
        goals=_inline_goal_session(brain, player),
        player=player,
    )


def _verifying_brain():
    """A brain whose two looks agree: the one path that earns the music."""
    return _LocatingBrain(sighting_json(), json.dumps(STILL_THERE))


