def _decode(wav_bytes):
    pcm, rate, channels, width = audio_io.decode_wav(wav_bytes)
    frames = len(pcm) // (channels * width)
    return pcm, rate, channels, width, frames / float(rate)


def test_the_acknowledgement_is_a_valid_bounded_pcm16_wav():
    pcm, rate, channels, width, seconds = _decode(media_cues.engagement_ack_wav())

    assert rate == media_cues.CUE_SAMPLE_RATE
    assert channels == audio_io.CHANNELS == 1
    assert width == audio_io.SAMPLE_WIDTH == 2
    # A fraction of a second, and provably not silence.
    assert seconds == pytest.approx(media_cues.ENGAGEMENT_ACK_SECONDS, abs=0.01)
    assert 0.0 < seconds < 1.0
    assert max(pcm) > 0


def test_the_success_music_is_a_valid_bounded_pcm16_wav():
    pcm, rate, channels, width, seconds = _decode(media_cues.goal_success_wav())

    assert rate == media_cues.CUE_SAMPLE_RATE
    assert channels == 1
    assert width == audio_io.SAMPLE_WIDTH
    assert seconds == pytest.approx(media_cues.GOAL_SUCCESS_SECONDS, abs=0.01)
    assert 2.0 <= seconds <= 3.0
    assert seconds <= media_cues.MAX_CUE_SECONDS
    assert max(pcm) > 0


def test_the_music_is_clearly_longer_and_clearly_a_tune():
    ack = _decode(media_cues.engagement_ack_wav())[4]
    music = _decode(media_cues.goal_success_wav())[4]

    # Not a near thing: nobody hearing both could take one for the other.
    assert music > ack * 5
    # ...and it is several separately struck notes, at several pitches.
    assert len(media_cues.GOAL_SUCCESS_NOTES) >= 4
    assert len({frequency for frequency, _s in media_cues.GOAL_SUCCESS_NOTES}) >= 3


def test_the_cues_are_deterministic_and_need_no_asset_on_disk():
    assert media_cues.engagement_ack_wav() == media_cues.engagement_ack_wav()
    assert media_cues.goal_success_wav() == media_cues.goal_success_wav()
    assert media_cues.engagement_ack_wav() != media_cues.goal_success_wav()


def test_the_cue_vocabulary_is_two_literal_functions_wide():
    """No registry, no name lookup, no path a model could ever select."""
    source = (Path(__file__).resolve().parent.parent / "src" / "media_cues.py").read_text()

    # Prose about determinism is fine; a call that reads a file or draws a
    # random number is not.
    for forbidden in ("eval(", "exec(", "getattr(", "importlib", "open(", "import random"):
        assert forbidden not in source
    for forbidden in ("import openai", "import character", "import pybullet", "import cv2"):
        assert forbidden not in source
    # Exactly two public callables of its own: one SFX, one tune.
    assert [
        name
        for name, value in vars(media_cues).items()
        if not name.startswith("_")
        and callable(value)
        and getattr(value, "__module__", None) == "media_cues"
    ] == ["engagement_ack_wav", "goal_success_wav"]


def test_an_overlong_cue_is_refused_rather_than_generated():
    """The bound is checked while the buffer is built, not merely documented."""
    rate = media_cues.CUE_SAMPLE_RATE
    too_long = b"\x00\x00" * int((media_cues.MAX_CUE_SECONDS + 1.0) * rate)

    with pytest.raises(RuntimeError, match="outside"):
        media_cues._cue(too_long, rate)


