@pytest.mark.parametrize(
    "cue, label",
    [(ACK, "engagement acknowledgement"), (MUSIC, "success music")],
    ids=["sfx", "music"],
)
def test_a_cue_extends_the_shared_quiet_deadline_and_shuts_the_microphone(cue, label):
    session = VoiceSession(turn=None, spawn=lambda _work: None)
    player = CuePlayer(cue_seconds=2.0)
    now = time.monotonic()

    assert session.ready(now) is True
    assert engagement_demo._play_cue(player, session, cue, label) is True

    # The lamp is making a noise, so it is "speaking" for this purpose...
    assert session.speaking(time.monotonic()) is True
    assert session.ready(time.monotonic()) is False
    # ...and a push-to-talk request cannot start a turn while it lasts.
    assert session.start(1, time.monotonic()) is False
    assert session.busy is False
    # Once the cue has elapsed, ordinary turns work again.
    assert session.ready(time.monotonic() + 3.0) is True
    assert session.start(1, time.monotonic() + 3.0) is True


def test_a_cue_that_could_not_be_played_holds_the_microphone_shut_for_nothing():
    session = VoiceSession(turn=None, spawn=lambda _work: None)
    player = CuePlayer(cue_seconds=2.0, fail_on=(ACK,))

    assert engagement_demo._play_cue(player, session, ACK, "engagement acknowledgement") is False
    assert session.speaking(time.monotonic()) is False
    assert session.ready(time.monotonic()) is True


def test_a_cue_is_skipped_rather_than_layered_over_the_shared_speaker():
    """Everything else that owns the player keeps the decoration quiet."""
    session = VoiceSession(turn=None, spawn=lambda _work: None)
    now = time.monotonic()
    assert engagement_demo._speaker_free(session, None, now) is True

    # Mid-sentence: the reply is still coming out of the speaker.
    session.mark_speaking(5.0, now)
    assert engagement_demo._speaker_free(session, None, now) is False
    assert engagement_demo._speaker_free(session, None, now + 6.0) is True

    # A goal that still owns the shared player, even after being abandoned.
    goals = _inline_goal_session(_LocatingBrain(sighting_json()))
    goals.request(goal_module.Goal(kind="find_and_light", target="mug"), 1)
    assert engagement_demo._speaker_free(None, goals, now) is False
    goals.finish()
    assert engagement_demo._speaker_free(None, goals, now) is True


def test_the_music_is_armed_only_by_a_goal_that_reached_the_closing_line():
    """`succeeded` is legal from HOLD and nowhere else."""
    goals = _inline_goal_session(_verifying_brain())

    assert goals.succeeded() is False           # no goal at all
    goals.request(goal_module.Goal(kind="find_and_light", target="mug"), 1)
    assert goals.succeeded() is False           # accepted, but nothing verified
    assert goals.music_pending is False

    goals.hold(goal_module.found_line("mug"))
    assert goals.succeeded() is True
    assert goals.music_pending is True

    # Played once, and never twice.
    goals.music_played()
    assert goals.music_pending is False
    # ...and a goal that ends drops the bit with everything else it held.
    goals.succeeded()
    goals.finish()
    assert goals.music_pending is False
